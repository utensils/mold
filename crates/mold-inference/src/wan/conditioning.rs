//! Image conditioning for the two current-generation Wan I2V paths.
//!
//! Pure tensor assembly: nothing here loads weights or touches a device beyond
//! the one its inputs already live on. The VAE encode that produces the
//! condition latent (`sample_mode="argmax"` plus the per-channel
//! `(latent - mean) / std`) belongs to the VAE layer and arrives here as an
//! input.
//!
//! The two paths condition in opposite directions, and **their masks have
//! opposite polarity**:
//!
//! | | A14B / 2.1 channel-concat | TI2V-5B latent inpaint |
//! |---|---|---|
//! | mask at latent frame 0 | **1** | **0** |
//! | mask elsewhere | 0 | 1 |
//! | consumed by | `cat([mask4, latent], dim=1)` | `(1 - m) * cond + m * latents` |
//!
//! Feeding one path the other's mask conditions exactly the wrong frames and
//! still renders plausible video, so the two are separate types here rather
//! than one shared helper with a flag.
//!
//! Golden values come from diffusers 0.38.0 (`pipeline_wan_i2v.py`), captured
//! in `tmp/wan-research/wani2v-golden.json` and `wanti2v-golden.json`.

use anyhow::{bail, Result};
use candle_core::{DType, Device, Tensor};

/// Latent grid a conditioning build targets.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct WanLatentGeometry {
    pub latent_frames: usize,
    pub latent_height: usize,
    pub latent_width: usize,
}

impl WanLatentGeometry {
    /// Derive the latent grid from pixel dimensions.
    ///
    /// `temporal_scale` is 4 for both VAE generations; `spatial_scale` is 8
    /// (2.1) or 16 (2.2).
    pub fn from_pixels(
        frames: u32,
        height: u32,
        width: u32,
        temporal_scale: usize,
        spatial_scale: usize,
    ) -> Result<Self> {
        validate_frame_grid(frames, temporal_scale)?;
        if spatial_scale == 0 {
            bail!("Wan conditioning: spatial scale must be positive");
        }
        if !(height as usize).is_multiple_of(spatial_scale)
            || !(width as usize).is_multiple_of(spatial_scale)
        {
            bail!(
                "Wan conditioning: {height}x{width} is not a multiple of the {spatial_scale}x \
                 VAE spatial stride"
            );
        }
        Ok(Self {
            latent_frames: (frames as usize - 1) / temporal_scale + 1,
            latent_height: height as usize / spatial_scale,
            latent_width: width as usize / spatial_scale,
        })
    }
}

/// Frames must sit on the family's `k*step + 1` grid.
///
/// Delegates the step to `mold_core`, which already owns the family table, so
/// the two cannot drift.
pub(crate) fn validate_frame_grid(frames: u32, temporal_scale: usize) -> Result<()> {
    debug_assert_eq!(
        mold_core::validation::frame_step_for_family("wan"),
        Some(mold_core::validation::WAN_TEMPORAL_SCALE),
        "mold-core must still own the wan frame step"
    );
    if temporal_scale == 0 {
        bail!("Wan conditioning: temporal scale must be positive");
    }
    if frames == 0 || !(frames as usize - 1).is_multiple_of(temporal_scale) {
        bail!(
            "Wan requires a {temporal_scale}k+1 frame count (1, {}, {}, ...), got {frames}",
            temporal_scale + 1,
            2 * temporal_scale + 1
        );
    }
    Ok(())
}

/// Pixel dimensions must clear the VAE stride *and* the DiT patch, because the
/// transformer patches the latent again on top of the VAE's downsample.
///
/// **mold does not implement upstream's area bucketing.** `image2video.py`
/// resizes a source image to fit a `max_area` budget, and that arithmetic is
/// float-fragile: an 832x480 source at Wan's own `832*480` bucket comes out
/// 832x**464**, because `sqrt(max_area * h/w)` lands one ULP below 480 and the
/// following floor-divide drops a whole stride. mold honours the requested
/// width and height instead, per the server's dimension contract. See issue
/// #746 before "fixing" any resolution mismatch against upstream or ComfyUI.
pub(crate) fn validate_conditioning_dimensions(
    height: u32,
    width: u32,
    spatial_scale: usize,
    patch: usize,
) -> Result<()> {
    if spatial_scale == 0 || patch == 0 {
        bail!("Wan conditioning: spatial scale and patch size must be positive");
    }
    let grid = spatial_scale * patch;
    if !(height as usize).is_multiple_of(grid) || !(width as usize).is_multiple_of(grid) {
        bail!(
            "Wan requires width and height to be multiples of {grid} \
             ({spatial_scale}x VAE stride times the {patch}x DiT patch), got {width}x{height}"
        );
    }
    Ok(())
}

// ---------------------------------------------------------------------------
// A14B-style channel-concat conditioning
// ---------------------------------------------------------------------------

/// Which pixel frames the caller supplied an image for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum WanImageAnchors {
    /// Image-to-video: only pixel frame 0 is given.
    FirstFrame,
    /// First-last-frame interpolation: pixel frames 0 and F-1 are given.
    FirstAndLastFrame,
}

/// The 4-channel grouped mask that rides alongside the condition latent.
///
/// Upstream builds it by tensor gymnastics (`pipeline_wan_i2v.py:467-475`):
/// start from a per-*pixel*-frame mask, repeat frame 0 four times, concatenate
/// the rest, then `view(B, -1, 4, h, w).transpose(1, 2)`. That collapses to a
/// closed form — mask channel `c` of latent frame `g` is temporal entry
/// `4g + c` of
///
/// ```text
/// [1, 1, 1, 1] ++ [0; pixel frames 1..]      (with the last entry 1 for FLF2V)
/// ```
///
/// which is what this builds. The golden tests prove the two agree.
///
/// **The FLF2V trailing flag lands in channel 3 of the last latent frame and
/// nowhere else** — channels 0..2 of that frame stay 0. That is a consequence
/// of the 4-way grouping, not a "mask the last latent frame" rule; setting all
/// four channels is wrong.
pub(crate) fn build_a14b_mask(
    pixel_frames: usize,
    anchors: WanImageAnchors,
    geometry: WanLatentGeometry,
    temporal_scale: usize,
    device: &Device,
    dtype: DType,
) -> Result<Tensor> {
    if temporal_scale == 0 {
        bail!("Wan conditioning: temporal scale must be positive");
    }
    if pixel_frames == 0 || !(pixel_frames - 1).is_multiple_of(temporal_scale) {
        bail!(
            "Wan conditioning: {pixel_frames} pixel frames is not on the {temporal_scale}k+1 grid"
        );
    }
    if anchors == WanImageAnchors::FirstAndLastFrame && pixel_frames < 2 {
        bail!("Wan conditioning: a first-and-last-frame render needs at least 2 pixel frames");
    }
    let expected = temporal_scale * geometry.latent_frames;
    // 4 copies of frame 0, then pixel frames 1.. — exactly 4 * latent_frames.
    let entries = temporal_scale + (pixel_frames - 1);
    if entries != expected {
        bail!(
            "Wan conditioning: {pixel_frames} pixel frames grouped to {entries} mask entries but \
             the latent grid needs {expected}"
        );
    }

    let mut temporal = vec![0f32; entries];
    for slot in temporal.iter_mut().take(temporal_scale) {
        *slot = 1.0;
    }
    if anchors == WanImageAnchors::FirstAndLastFrame {
        // The final pixel frame keeps its 1 (upstream zeroes only 1..F-1).
        let last = entries - 1;
        temporal[last] = 1.0;
    }

    let (frames, height, width) = (
        geometry.latent_frames,
        geometry.latent_height,
        geometry.latent_width,
    );
    let mut values = Vec::with_capacity(temporal_scale * frames * height * width);
    for channel in 0..temporal_scale {
        for frame in 0..frames {
            let flag = temporal[temporal_scale * frame + channel];
            values.extend(std::iter::repeat_n(flag, height * width));
        }
    }
    Tensor::from_vec(values, (1, temporal_scale, frames, height, width), device)?
        .to_dtype(dtype)
        .map_err(Into::into)
}

/// Assemble the conditioning half of the DiT input: `cat([mask, latent], dim=1)`.
///
/// **Mask first.** With the shipped 2.1 VAE that is 4 mask + 16 latent = 20
/// channels, and the model input is `cat([noise(16), conditioning(20)])` = the
/// 36 channels an I2V checkpoint declares.
pub(crate) fn build_a14b_conditioning(
    condition_latent: &Tensor,
    pixel_frames: usize,
    anchors: WanImageAnchors,
    temporal_scale: usize,
) -> Result<Tensor> {
    let (batch, _, frames, height, width) = condition_latent.dims5()?;
    if batch != 1 {
        bail!("Wan conditioning: expected a single-sample condition latent, got batch {batch}");
    }
    let geometry = WanLatentGeometry {
        latent_frames: frames,
        latent_height: height,
        latent_width: width,
    };
    let mask = build_a14b_mask(
        pixel_frames,
        anchors,
        geometry,
        temporal_scale,
        condition_latent.device(),
        condition_latent.dtype(),
    )?;
    Tensor::cat(&[&mask, condition_latent], 1).map_err(Into::into)
}

// ---------------------------------------------------------------------------
// TI2V-5B latent inpaint
// ---------------------------------------------------------------------------

/// The TI2V-5B conditioning: latent frame 0 is held at the clean encoded image
/// while every other frame denoises.
///
/// **The mask is 0 at latent frame 0 and 1 everywhere else** — the inverse of
/// [`build_a14b_mask`]. It reads as "which frames are still noisy", because it
/// is used as `(1 - mask) * condition + mask * latents` and as a direct
/// multiplier on the timestep.
#[derive(Debug, Clone)]
pub(crate) struct WanTi2vInpaint {
    /// `[1, 1, latent_frames, h, w]`.
    mask: Tensor,
    geometry: WanLatentGeometry,
}

impl WanTi2vInpaint {
    pub fn new(geometry: WanLatentGeometry, device: &Device, dtype: DType) -> Result<Self> {
        let WanLatentGeometry {
            latent_frames,
            latent_height,
            latent_width,
        } = geometry;
        if latent_frames == 0 || latent_height == 0 || latent_width == 0 {
            bail!("Wan TI2V conditioning: latent grid {geometry:?} is empty");
        }
        if latent_frames == 1 {
            // Every token would be frame 0, so the whole per-token timestep
            // vector is zero and the sampler denoises nothing.
            bail!(
                "Wan TI2V conditioning: a single latent frame leaves nothing to denoise — the \
                 conditioning image occupies the entire clip. Ask for more than \
                 {} frames.",
                mold_core::validation::WAN_TEMPORAL_SCALE
            );
        }
        let per_frame = latent_height * latent_width;
        let mut values = vec![1f32; latent_frames * per_frame];
        for slot in values.iter_mut().take(per_frame) {
            *slot = 0.0;
        }
        let mask = Tensor::from_vec(
            values,
            (1, 1, latent_frames, latent_height, latent_width),
            device,
        )?
        .to_dtype(dtype)?;
        Ok(Self { mask, geometry })
    }

    pub fn mask(&self) -> &Tensor {
        &self.mask
    }

    pub fn geometry(&self) -> WanLatentGeometry {
        self.geometry
    }

    /// `(1 - mask) * condition + mask * latents` — the clean first frame from
    /// `condition`, everything else from the sampler's current latents.
    ///
    /// Used both to build the transformer input each step and, with the same
    /// arithmetic, to re-impose the clean frame on the sampler's output; see
    /// [`Self::reimpose_clean_frame`].
    pub fn blend(&self, condition: &Tensor, latents: &Tensor) -> Result<Tensor> {
        self.check_operand(condition, "condition")?;
        self.check_operand(latents, "latents")?;
        let keep = self.mask.to_dtype(latents.dtype())?;
        let inverse = keep.affine(-1.0, 1.0)?;
        Ok(condition
            .broadcast_mul(&inverse)?
            .add(&latents.broadcast_mul(&keep)?)?)
    }

    /// Re-impose the clean conditioning frame after a sampler step
    /// (`textimage2video.py:598`). Identical arithmetic to [`Self::blend`],
    /// named separately because the two call sites mean different things and
    /// dropping the post-step one silently lets frame 0 drift.
    pub fn reimpose_clean_frame(&self, condition: &Tensor, latents: &Tensor) -> Result<Tensor> {
        self.blend(condition, latents)
    }

    /// Per-token timestep vector: 0 for the tokens of latent frame 0, `t` for
    /// every other token, padded with `t` out to `seq_len`.
    ///
    /// Upstream writes it as `(mask[0][0][:, ::2, ::2] * t).flatten()`, where
    /// the `::2` subsample is the DiT patch size — so the length is one entry
    /// per *token*, not per latent pixel. `seq_len` padding only matters when
    /// the caller rounds the sequence up (upstream does it for
    /// sequence-parallel splits, `textimage2video.py:573-578`); diffusers omits
    /// it because its `seq_len` already equals the token count.
    pub fn per_token_timesteps(
        &self,
        timestep: f64,
        patch: usize,
        seq_len: Option<usize>,
        device: &Device,
        dtype: DType,
    ) -> Result<Tensor> {
        if patch == 0 {
            bail!("Wan TI2V conditioning: patch size must be positive");
        }
        let tokens_per_frame = self.geometry.latent_height.div_ceil(patch)
            * self.geometry.latent_width.div_ceil(patch);
        let tokens = tokens_per_frame * self.geometry.latent_frames;
        let total = match seq_len {
            None => tokens,
            Some(len) if len >= tokens => len,
            Some(len) => bail!(
                "Wan TI2V conditioning: seq_len {len} is shorter than the {tokens} tokens this \
                 latent grid produces"
            ),
        };
        let mut values = vec![timestep as f32; total];
        for slot in values.iter_mut().take(tokens_per_frame) {
            *slot = 0.0;
        }
        Tensor::from_vec(values, (1, total), device)?
            .to_dtype(dtype)
            .map_err(Into::into)
    }

    fn check_operand(&self, tensor: &Tensor, label: &str) -> Result<()> {
        let (_, _, frames, height, width) = tensor.dims5()?;
        let expected = self.geometry;
        if frames != expected.latent_frames
            || height != expected.latent_height
            || width != expected.latent_width
        {
            bail!(
                "Wan TI2V conditioning: {label} is {frames}x{height}x{width} but the mask covers \
                 {}x{}x{}",
                expected.latent_frames,
                expected.latent_height,
                expected.latent_width
            );
        }
        Ok(())
    }
}

