    /// mold honours the requested dimensions; upstream's area bucketing would
    /// silently resize. Pin the divergence so nobody "fixes" it by accident —
    /// notably 832x480, whose height upstream drops to 464. See issue #746.
    #[test]
    fn upstream_bucketing_diverges_and_is_deliberately_not_implemented() {
        let mut shrinking = 0;
        for (image_h, image_w, _area, upstream_h, upstream_w) in UPSTREAM_BUCKETING {
            // Whatever upstream would have produced, our validator either
            // accepts the caller's own dimensions or rejects them outright; it
            // never rewrites them.
            if (*image_h, *image_w) != (*upstream_h, *upstream_w) {
                shrinking += 1;
            }
        }
        assert!(
            shrinking > 0,
            "the fixture must contain at least one case where upstream resizes"
        );

        // The headline case: a 480x832 source at its own bucket loses 16px of
        // height upstream. mold accepts 480x832 unchanged.
        let (h, w, _, up_h, up_w) = UPSTREAM_BUCKETING
            .iter()
            .find(|(h, w, _, _, _)| (*h, *w) == (480, 832))
            .copied()
            .expect("the 480x832 case must be recorded");
        assert_eq!((up_h, up_w), (464, 832), "upstream shrinks the height");
        validate_conditioning_dimensions(h, w, 8, 2)
            .expect("mold accepts the requested dimensions as-is");
    }

