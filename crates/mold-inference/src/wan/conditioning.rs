    fn tensor(values: &[f64], shape: (usize, usize, usize, usize, usize)) -> Tensor {
        let data: Vec<f32> = values.iter().map(|v| *v as f32).collect();
        Tensor::from_vec(data, shape, &cpu()).unwrap()
    }

    /// Goldens carry the fixture's f64 precision; the module runs in f32.
    fn max_abs_diff(got: &[f32], want: &[f64]) -> f64 {
        assert_eq!(got.len(), want.len(), "length mismatch");
        got.iter()
            .zip(want)
            .map(|(a, b)| (f64::from(*a) - b).abs())
            .fold(0.0f64, f64::max)
    }

